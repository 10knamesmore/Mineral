//! `mineral ctl` — 面向脚本与全局键的 daemon 控制面。
//!
//! 命令都走控制请求(不需要歌曲身份):提交后把会话结论翻成一条结构化结论,人读一行文本或
//! `--json` 一行信封,退出码区分「已应用」「被拒」「没执行」。
//!
//! 三条命令需要提交前读状态:`play-pause` 要知道有没有当前曲、在播与否;相对音量要知道当前
//! 百分比;相对跳要知道位置与时长。它们先等对应订阅的首帧,读不到就报「没执行」,不猜默认值。
//!
//! 连不上 daemon、握手被拒都算「没执行」(退出码 3),不当作 CLI 自身错误;参数错误由 clap
//! 拦截(退出码 2)。

